/**
 * Website -> wiki. Writes a generated digest of what the team did in the app to
 * ../wiki/exports/website-activity.md: items edited or added in the app, suggestions,
 * decisions, stances and checklist state. Regenerate, never hand-edit.
 *   npx tsx scripts/export-activity.ts
 * Uses DATABASE_URL if set (production), else the local PGlite database.
 * Only first names are written; no emails or credentials.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { db, schema } from "../src/db";

const OUT = join(__dirname, "../../wiki/exports/website-activity.md");
const first = (n?: string | null) => (n ? n.split(" ")[0] : "unknown");
const day = (d?: Date | null) => (d ? d.toISOString().slice(0, 10) : "");

async function main() {
  const d = await db();
  const { items, suggestions, decisions, checklist, stances, users, polls, pollOptions } = schema;
  const names = new Map((await d.select({ id: users.id, name: users.name }).from(users)).map((u) => [u.id, first(u.name)]));
  const who = (id?: string | null) => (id ? names.get(id) ?? "unknown" : "unknown");

  const all = await d.select().from(items);
  const edited = all.filter((i) => i.updatedBy || i.origin === "app");
  const subs = await d.select().from(suggestions);
  const decs = await d.select().from(decisions);
  const todo = await d.select().from(checklist);
  const st = await d.select().from(stances);
  const pl = await d.select().from(polls);
  const opts = await d.select().from(pollOptions);

  const L: string[] = [];
  L.push(
    "---",
    'title: "Website Activity (generated)"',
    "type: export",
    "tags: [website, generated]",
    "related:",
    "  - sprint/team-brief.md",
    "  - people/our-team.md",
    "sources:",
    "  - sources/team/ai-collusion-team-brief.html",
    `updated: ${day(new Date())}`,
    "---",
    "",
    "# Website Activity",
    "",
    "> Generated digest of what the team wrote in the website (edits, suggestions, decisions, stances, checklist). Regenerated by `outskiller-website/scripts/export-activity.ts`; do not hand-edit. Content is team-written in the app, not sourced from `sources/`.",
    "",
    `_Exported ${new Date().toISOString()}._`,
    "",
  );

  L.push("## Items edited or added in the app", "");
  if (!edited.length) L.push("None yet.", "");
  for (const i of edited) L.push(`### ${i.title}`, "", `${i.kind} · ${i.origin} · v${i.version} · ${who(i.updatedBy)}, ${day(i.updatedAt)}`, "", i.body.trim(), "");

  L.push("## Suggestions", "");
  if (!subs.length) L.push("None yet.", "");
  for (const s of subs) {
    const target = s.itemId ? all.find((i) => i.id === s.itemId)?.title ?? `item ${s.itemId}` : `new ${s.kind}`;
    L.push(`- **${s.type}** on ${target} by ${who(s.authorId)} (${s.status}, ${day(s.createdAt)}): ${s.note || s.proposed.title || ""}${s.reply ? ` Reply: ${s.reply}` : ""}`);
  }
  L.push("");

  L.push("## Decisions", "");
  for (const x of decs) L.push(`- ${x.label}: ${x.value ?? "_not decided_"}${x.value ? ` (${who(x.by)}, ${day(x.at)})` : ""}`);
  L.push("");

  L.push("## Plan polls and stances", "");
  for (const p of pl) {
    L.push(`**${p.title}** (${p.status})`, "");
    for (const o of opts.filter((o) => o.pollId === p.id)) {
      const votes = st.filter((s) => s.target === `option:${o.id}`);
      L.push(`- ${o.label}: ${votes.length ? votes.map((v) => `${who(v.userId)} ${v.stance}`).join(", ") : "no votes"}`);
    }
    L.push("");
  }
  const angles = st.filter((s) => s.target.startsWith("angle:"));
  if (angles.length) {
    L.push("**Angle stances**", "");
    for (const t of [...new Set(angles.map((a) => a.target))].sort()) L.push(`- ${t.slice(6)}: ${angles.filter((a) => a.target === t).map((a) => `${who(a.userId)} ${a.stance}`).join(", ")}`);
    L.push("");
  }

  L.push("## Checklist", "");
  for (const c of todo.sort((a, b) => a.sort - b.sort)) L.push(`- [${c.done ? "x" : " "}] ${c.label}${c.ownerId ? ` (${who(c.ownerId)})` : ""}`);
  L.push("", "## Related", "", "- [Team brief](../sprint/team-brief.md)", "- [Our team](../people/our-team.md)", "", "## Sources", "", "- [Team brief](../../sources/team/ai-collusion-team-brief.html): the seed the website started from", "");

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, L.join("\n"));
  console.log(`exported: ${edited.length} edited items, ${subs.length} suggestions, ${decs.filter((x) => x.value).length} decisions, ${st.length} stances, ${todo.length} checklist items -> ${OUT}`);
}
main().then(() => process.exit(0), (e) => { console.error(e); process.exit(1); });
